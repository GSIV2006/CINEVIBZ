export function textContains(text: string, term: string) {
  const normalize = (s: string) =>
    s
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, ' ')
      .trim();
  return (' ' + normalize(text) + ' ').includes(' ' + normalize(term) + ' ');
}
